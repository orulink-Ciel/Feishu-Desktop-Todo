import { chromium } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const cli = path.join(process.env.APPDATA, 'npm/node_modules/@larksuite/cli/bin/lark-cli.exe');
const guid = '6fadcf43-c4dc-404b-b924-157bf97922d7';
const run = args => JSON.parse(execFileSync(cli, args, { encoding: 'utf8', windowsHide: true, timeout: 30000, env: { ...process.env, LARKSUITE_CLI_NO_UPDATE_NOTIFIER: '1', LARKSUITE_CLI_NO_SKILLS_NOTIFIER: '1' } }));
const read = () => run(['task','tasks','get','--as','user','--task-guid',guid,'--format','json']).data.task;
const before = read();
if (!before.summary.startsWith('【同步验证】') || before.members.filter(m => m.role === 'assignee').length !== 1) throw new Error('Not the isolated verification task');
run(['task','+reopen','--as','user','--task-id',guid,'--format','json']);
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223');
const pages = browser.contexts().flatMap(context => context.pages());
const page = pages.find(page => page.url().includes('127.0.0.1:1420'));
if (!page) throw new Error(`Desktop page missing: ${pages.map(page => page.url()).join(',')}`);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.getByRole('heading', { name: '今日待办' }).waitFor();
if (await page.getByText('浏览器预览 · 示例数据，操作不会写入飞书').count()) throw new Error('Native application incorrectly using preview data');
await page.getByRole('button', { name: '刷新', exact: true }).click();
await page.getByRole('button', { name: before.summary, exact: true }).waitFor();
await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
await page.screenshot({ path: `${root}/artifacts/desktop-live-before.png` });
const beforeSnapshot = await page.evaluate(() => window.__TAURI_INTERNALS__.invoke('get_snapshot'));
const nativeTask = beforeSnapshot.tasks.find(task => task.guid === guid);
if (!nativeTask || !beforeSnapshot.auth.canWrite) throw new Error('Native bridge did not load authorized real task');
await page.getByRole('button', { name: `固定：${before.summary}`, exact: true }).click();
await page.waitForFunction(async ({ guid, wasPinned }) => {
  const snapshot = await window.__TAURI_INTERNALS__.invoke('get_snapshot');
  return Boolean(snapshot.tasks.find(task => task.guid === guid)?.pinnedDate) !== wasPinned;
}, { guid, wasPinned: Boolean(nativeTask.pinnedDate) }, { polling: 300, timeout: 15000 });
await page.getByRole('button', { name: `完成：${before.summary}`, exact: true }).click();
await page.getByText('飞书已确认完成', { exact: true }).waitFor({ timeout: 40000 });
const after = read();
if (after.guid !== guid || after.status !== 'done' || Number(after.completed_at) <= 0) throw new Error('Native click did not complete remote task');
if (await page.getByRole('button', { name: before.summary, exact: true }).count()) throw new Error('Confirmed completion did not leave pending view');
await page.getByRole('button', { name: '窗口置顶', exact: true }).click();
await page.waitForFunction(async () => {
  const snapshot = await window.__TAURI_INTERNALS__.invoke('get_snapshot');
  return snapshot.preferences.alwaysOnTop === true;
});
await page.waitForFunction(() => window.__TAURI_INTERNALS__.invoke('plugin:window|is_always_on_top', { label: 'main' }), null, { polling: 300, timeout: 15000 });
await page.getByRole('button', { name: '窗口置顶', exact: true }).click();
await page.waitForFunction(async () => !(await window.__TAURI_INTERNALS__.invoke('plugin:window|is_always_on_top', { label: 'main' })), null, { polling: 300, timeout: 15000 });
await page.getByRole('button', { name: '设置', exact: true }).click();
await page.getByLabel('自动同步间隔').selectOption('120');
await page.waitForFunction(async () => (await window.__TAURI_INTERNALS__.invoke('get_snapshot')).preferences.intervalSeconds === 120);
await page.getByLabel('自动同步间隔').selectOption('300');
await page.waitForFunction(async () => (await window.__TAURI_INTERNALS__.invoke('get_snapshot')).preferences.intervalSeconds === 300);
await page.getByRole('button', { name: '设置', exact: true }).click();
await page.screenshot({ path: `${root}/artifacts/desktop-live-final.png` });
const result = { passed: true, realUser: beforeSnapshot.auth.userName, initialPending: beforeSnapshot.tasks.length, finalRemoteStatus: after.status, testGuid: guid, checks: ['real_tauri_bridge', 'real_task_render', 'local_pin_readback', 'native_ui_complete_remote_readback', 'completed_task_removed', 'actual_native_always_on_top_toggle', 'interval_preference'], pageErrors: errors };
if (errors.length) throw new Error(JSON.stringify(result));
await writeFile(new URL('../artifacts/desktop-check.json', import.meta.url), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
await page.getByRole('button', { name: '退出', exact: true }).click();
await browser.close();
