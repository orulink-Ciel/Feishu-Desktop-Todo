import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const artifacts = new URL('../artifacts/', import.meta.url);
await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 420, height: 700 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:1420/');
await page.getByRole('heading', { name: '今日待办' }).waitFor();
await page.getByText('浏览器预览 · 示例数据，操作不会写入飞书').waitFor();
await page.getByRole('button', { name: '完善机器人复刻指南，从 PCB 到整机', exact: true }).waitFor();
await page.screenshot({ path: `${root}/artifacts/preview-today.png` });
await page.getByRole('button', { name: '此前到期' }).click();
await page.getByRole('button', { name: '完成语音助手最佳实践文档', exact: true }).waitFor();
await page.getByRole('button', { name: /^全部/ }).click();
await page.getByRole('button', { name: '固定：下周工作坊的设备与资料准备', exact: true }).click();
await page.getByRole('button', { name: /^今天/ }).click();
await page.getByRole('button', { name: '下周工作坊的设备与资料准备', exact: true }).waitFor();
await page.getByRole('button', { name: '完成：整理今天的面试问题与沟通记录', exact: true }).click();
await page.getByText('提交中', { exact: true }).waitFor();
await page.getByText('示例任务已完成').waitFor();
if (await page.getByRole('button', { name: '整理今天的面试问题与沟通记录', exact: true }).count()) throw new Error('Completed example still visible');
await page.getByRole('button', { name: /^全部/ }).click();
await page.getByRole('textbox', { name: '搜索任务' }).fill('收集应用测试');
await page.getByRole('button', { name: '收集应用测试反馈', exact: true }).waitFor();
await page.setViewportSize({ width: 360, height: 500 });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
if (overflow || errors.length) throw new Error(JSON.stringify({ overflow, errors }));
await writeFile(new URL('preview-check.json', artifacts), JSON.stringify({ passed: true, checks: ['explicit_demo_label', 'today_view', 'overdue_expand', 'future_pin', 'pending_then_confirmed', 'search', '360px_no_overflow'], pageErrors: errors }, null, 2));
await browser.close();
console.log('Preview UI checks passed');
