import { chromium } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
const cli = path.join(process.env.APPDATA, 'npm/node_modules/@larksuite/cli/bin/lark-cli.exe');
const guid = '6fadcf43-c4dc-404b-b924-157bf97922d7';
const run = args => JSON.parse(execFileSync(cli, args, { encoding: 'utf8', windowsHide: true, timeout: 30000, env: { ...process.env, LARKSUITE_CLI_NO_UPDATE_NOTIFIER: '1', LARKSUITE_CLI_NO_SKILLS_NOTIFIER: '1' } }));
const before = run(['task','tasks','get','--as','user','--task-guid',guid,'--format','json']).data.task;
if (!before.summary.startsWith('【同步验证】') || before.status !== 'done') throw new Error('Verification task setup invalid');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223');
const page = browser.contexts().flatMap(context => context.pages()).find(page => page.url().includes('127.0.0.1:1420'));
if (!page) throw new Error('Desktop page missing');
await page.getByRole('heading', { name: '今日待办' }).waitFor();
const cache = await page.evaluate(() => window.__TAURI_INTERNALS__.invoke('get_snapshot'));
if (!cache.lastSyncedAt || !cache.auth.userId) throw new Error('Restart did not restore account cache');
await page.getByRole('button', { name: '设置', exact: true }).click();
await page.getByLabel('自动同步间隔').selectOption('120');
await page.waitForFunction(async () => (await window.__TAURI_INTERNALS__.invoke('get_snapshot')).preferences.intervalSeconds === 120);
await page.getByRole('button', { name: '设置', exact: true }).click();
const reopenAt = Date.now();
run(['task','+reopen','--as','user','--task-id',guid,'--format','json']);
await page.getByRole('button', { name: before.summary, exact: true }).waitFor({ timeout: 150000 });
const reopenedAt = Date.now();
const reopened = await page.evaluate(() => window.__TAURI_INTERNALS__.invoke('get_snapshot'));
if (reopened.tasks.find(task => task.guid === guid)?.pinnedDate !== new Intl.DateTimeFormat('en-CA', { timeZone:'Asia/Shanghai', year:'numeric',month:'2-digit',day:'2-digit' }).format(new Date())) throw new Error('Local pin not retained across application restart');
run(['task','+complete','--as','user','--task-id',guid,'--format','json']);
await page.getByRole('button', { name: before.summary, exact: true }).waitFor({ state: 'detached', timeout: 150000 });
const finishedAt = Date.now();
await page.getByRole('button', { name: '设置', exact: true }).click();
await page.getByLabel('自动同步间隔').selectOption('300');
await page.waitForFunction(async () => (await window.__TAURI_INTERNALS__.invoke('get_snapshot')).preferences.intervalSeconds === 300);
await page.getByRole('button', { name: '设置', exact: true }).click();
const result = { passed:true, checks:['native_restart_cache','external_reopen_auto_sync','pin_survives_restart','external_complete_auto_sync'], reopenedVisibleMs:reopenedAt-reopenAt, remoteCompletedHiddenMs:finishedAt-reopenedAt };
await writeFile(new URL('../artifacts/desktop-sync-check.json', import.meta.url),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
await page.getByRole('button', { name:'退出',exact:true }).click();
await browser.close();
